$(document).ready(function(){
  $(".edit").click(function(){
    $(".date-box").slideDown();
    $(".edit").css("visibility","hidden");
  });
});
$(document).ready(function(){
  $(".date-box>.btn-close").click(function(){
    $(".date-box").slideUp();
    $(".edit").css("visibility","visible");
  });
});
